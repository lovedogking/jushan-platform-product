-- ============================================================
-- Flyway 迁移：芊熠 QY-Q8 → QY-Q3（名称 Q8 → Q3）
-- ============================================================
-- 相机实际型号为 Q3（注册时 model=Q3），之前误命名为 Q8。
-- 同时修正 capabilities：Q3 仅支持开闸/常开（不支持关闸/常关/抓拍）。
-- ============================================================

-- -----------------------------------------------------------------------------
-- 1. 芊熠 QY-Q8 → QY-Q3，capabilities 修正为 OPEN_GATE,KEEP_OPEN
-- -----------------------------------------------------------------------------
UPDATE device_model
SET name = 'Q3', code = 'QY-Q3',
    capabilities = 'OPEN_GATE,KEEP_OPEN',
    description = '芊熠 Q3 车牌识别相机（MQTT接入；继电器可开闸可常开不可关闸；关闸靠地感）'
WHERE code = 'QY-Q8';

-- -----------------------------------------------------------------------------
-- 2. 存量相机能力同步
-- -----------------------------------------------------------------------------
UPDATE device d
    INNER JOIN device_model m ON d.model_id = m.id
SET d.capabilities = m.capabilities
WHERE d.device_type = 'CAMERA'
  AND m.code = 'QY-Q3';
